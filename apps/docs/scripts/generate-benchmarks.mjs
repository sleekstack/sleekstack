// apps/bench/results/published.json -> content/docs/benchmarks.mdx. The snapshot is refreshed by hand, never by CI.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { contentDir } from './check-links.mjs'
import { repoRoot } from './entry-points.mjs'

export const publishedFile = join(repoRoot, 'apps/bench/results/published.json')
const SCENARIOS = 'https://github.com/sleekstack/sleekstack/blob/master/apps/bench/src/scenarios.ts'
const SUITES = {
  atoms: 'Atoms (reference: jotai)',
  reactivity: 'Reactive graphs: js-reactivity-benchmark and cellx shapes (reference: jotai)',
  jsfb: 'js-framework-benchmark operations in jsdom (reference: React; Solid and Qwik shown)',
  'render-string': 'String render (reference: React)',
  'render-dom': 'DOM render in jsdom (reference: React)',
  'jsx-overhead': 'JSX instance wrapper (reference: direct component calls)',
}

const ms = (n) => (n < 0.01 ? `${(n * 1000).toFixed(2)} µs` : `${n.toFixed(3)} ms`)

/** Renders the benchmarks page from a published results object. */
export function renderBenchmarks(results) {
  const bySuite = new Map()
  for (const c of results.cases) {
    const suite = c.case.split('/')[0]
    if (!bySuite.has(suite)) bySuite.set(suite, [])
    bySuite.get(suite).push(c)
  }
  const tables = Object.entries(SUITES)
    .filter(([suite]) => bySuite.has(suite))
    .map(([suite, title]) => {
      const cases = bySuite.get(suite)
      const swaps = cases.some((c) => c.swaps !== undefined)
      return [
        `## ${title}`,
        '',
        `| case | library | mean | p99 | rme | samples${swaps ? ' | node swaps' : ''} |`,
        `| --- | --- | ---: | ---: | ---: | ---:${swaps ? ' | ---:' : ''} |`,
        ...cases.map(
          (c) =>
            `| ${c.case.slice(suite.length + 1)} | ${c.library} | ${ms(c.mean)} | ${ms(c.p99)} | ±${c.rme.toFixed(2)}% | ${c.samples}${swaps ? ` | ${c.swaps ?? ''}` : ''} |`,
        ),
      ].join('\n')
    })
  const m = results.machine
  return `---
title: Benchmarks
description: SleekStack's renderer and atoms measured against React, jotai and effect-atom.
---

{/* Generated by scripts/generate-benchmarks.mjs from apps/bench/results/published.json. Do not edit. */}

These numbers come from one machine running one workload. Every library runs the same scenarios, defined in [scenarios.ts](${SCENARIOS}). The DOM suites run in jsdom, not a browser: compare them with React only, not with browser timings. Lower mean is faster.

Recorded ${results.publishedAt ?? ''} on Node ${m.node}, ${m.cpu}, ${m.os}.

The keyed-list update cases change one of 1,000 rows per write. \`keyed-update-data\` and \`keyed-update-handler\` (rows take an item object, or an item plus an inline \`on*\` handler) skip every unchanged row; \`keyed-update-render-callback\` passes a fresh render-time function to every row, so no row can skip and all 1,000 re-run. \`keyed-update-hook-miss\` and \`keyed-update-gen-miss\` do the same with rows that hold state (a hook, a nested component, an \`Effect.gen\` body), so all 1,000 run the full component path (the worst case).

Library versions: ${Object.entries(results.versions)
    .map(([k, v]) => `${k} ${v}`)
    .join(', ')}.

${tables.join('\n\n')}

To refresh this page, run \`pnpm --filter bench bench:json\` and then \`pnpm --filter bench publish-results\`.
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (!existsSync(publishedFile)) {
    console.error(
      `${publishedFile} is missing. Create it with: pnpm --filter bench bench:json && pnpm --filter bench publish-results`,
    )
    process.exit(1)
  }
  writeFileSync(join(contentDir, 'benchmarks.mdx'), renderBenchmarks(JSON.parse(readFileSync(publishedFile, 'utf8'))))
}
